#!/usr/bin/env bash
# Q-Bench runner for this Windows laptop (Git Bash). Started by run_qbench.cmd.
#
# Every step resumes, so re-running is cheap. On failure the runner waits for a
# RETRY file in this folder (Claude writes it after pushing a fix), pulls and
# restarts. Step names listed in a SKIP file (one per line) are skipped.
# After all stages it waits for CLEANUP (Claude writes it once the results
# are checked and pushed) and moves models/ into _to_delete/.
# Delete _to_delete/ yourself afterwards. Closing the window stops everything.
set -uo pipefail
cd "$(dirname "$0")" || exit 1
# keep every cache and temp file on this drive (never on C:)
mkdir -p .cache/tmp .cache/hf .cache/pip
export HF_HOME="$PWD/.cache/hf" PIP_CACHE_DIR="$PWD/.cache/pip" TEMP="$(cygpath -w "$PWD/.cache/tmp")"
export TMP="$TEMP" TMPDIR="$PWD/.cache/tmp"

REPO_URL=https://github.com/Bugeon151/Q-BENCH.git
BRANCH=feat/roadmap-v1
LLAMA_URL=https://github.com/ggml-org/llama.cpp
NEED_GB=${QB_NEED_GB:-230}   # estimate: models 7B ~62 + 1.5B ~13 + 3B ~25 + 14B ~120 GB (+ ~9 GB imatrix quants), venv/binaries ~3 GB
WAIT_SEC=43200      # 12 h for RETRY / CLEANUP
export PYTHONUTF8=1 PYTHONUNBUFFERED=1
PY=.venv/Scripts/python.exe

mkdir -p logs
if [ -z "${QB_TEED:-}" ]; then
  export QB_TEED=1
  exec > >(tee -a logs/runner.log) 2>&1
fi

status() {
  echo "[runner $(date '+%F %T')] $*"
  printf '%s %s\n' "$(date '+%F %T')" "$*" > STATUS.txt
}

step() {  # step NAME CMD...
  local name="$1" rc
  shift
  if [ -f SKIP ] && tr -d '\r' < SKIP | grep -qx "$name"; then status "SKIP $name"; return 0; fi
  status "START $name"
  "$@"
  rc=$?
  if [ "$rc" -eq 0 ]; then status "DONE $name"; else status "FAIL $name (exit $rc)"; fi
  return "$rc"
}

preflight() {
  command -v git >/dev/null || { echo "git not found"; return 1; }
  nvidia-smi --query-gpu=name,memory.total,driver_version --format=csv,noheader || return 1
  if command -v py >/dev/null && py -3.13 -c '' 2>/dev/null; then PYBOOT=(py -3.13)
  elif command -v py >/dev/null && py -3 -c 'import sys; assert sys.version_info >= (3, 10)' 2>/dev/null; then PYBOOT=(py -3)
  else
    local p
    p="$(cygpath -u "$LOCALAPPDATA")/Programs/Python/Python313/python.exe"
    [ -x "$p" ] || { echo "Python 3.10+ not found"; return 1; }
    PYBOOT=("$p")
  fi
  "${PYBOOT[@]}" -c 'import sys; print("python", sys.version.split()[0])'
  local free_kb used_kb
  free_kb=$(df -Pk . | awk 'NR==2 {print $4}')
  used_kb=$(du -sk models external/downloads 2>/dev/null | awk '{s += $1} END {print s + 0}')
  echo "disk: free $((free_kb / 1048576)) GB, already used by models/downloads $((used_kb / 1048576)) GB"
  if [ $(((free_kb + used_kb) / 1048576)) -lt "$NEED_GB" ]; then
    echo "need about $NEED_GB GB free on this drive"
    return 1
  fi
  "${PYBOOT[@]}" -c 'import ctypes
class S(ctypes.Structure):
    _fields_ = [("ac", ctypes.c_byte), ("flag", ctypes.c_byte), ("pct", ctypes.c_byte),
                ("saver", ctypes.c_byte), ("life", ctypes.c_ulong), ("full", ctypes.c_ulong)]
s = S(); ctypes.windll.kernel32.GetSystemPowerStatus(ctypes.byref(s))
print("power: AC" if s.ac == 1 else "WARNING: running on battery - plug in the charger for valid numbers")'
}

repo() {
  if [ ! -d .git ]; then
    git init -q && git config core.autocrlf false && git config core.longpaths true || return 1
    git remote add origin "$REPO_URL" || return 1
    printf '%s\n' STATUS.txt RETRY CLEANUP SKIP _to_delete/ .cache/ >> .git/info/exclude
    # keep existing files in this folder: point the branch at the remote commit without touching the worktree
    git fetch -q origin "$BRANCH" && git symbolic-ref HEAD "refs/heads/$BRANCH" && git reset -q FETCH_HEAD || return 1
    # tracked files that differ from the remote commit are backed up (and listed) before being replaced by it
    git diff --name-only | tee logs/first_sync_modified.txt | while IFS= read -r f; do
      mkdir -p "_to_delete/pre_sync/$(dirname "$f")" && cp -p "$f" "_to_delete/pre_sync/$f"
    done
    git checkout -q -- . || return 1
  else
    # derived outputs (regenerated by analyze.py) and config Claude may patch in place mid-run
    git checkout -q -- results data/processed config/experiment.yaml
    git fetch -q origin "$BRANCH" && git merge -q --ff-only FETCH_HEAD || return 1
  fi
  git log -1 --format='repo: %h %s'
}

llama_src() {
  local dir=external/llama.cpp pin
  pin="$(tr -d '[:space:]' < config/llama_cpp_commit.txt)"
  [ "$(git -C "$dir" rev-parse HEAD 2>/dev/null)" = "$pin" ] && return 0
  mkdir -p "$dir" && git -C "$dir" init -q || return 1
  git -C "$dir" config core.autocrlf false && git -C "$dir" config core.longpaths true
  git -C "$dir" remote get-url origin >/dev/null 2>&1 || git -C "$dir" remote add origin "$LLAMA_URL"
  git -C "$dir" fetch -q --depth 1 origin "$pin" && git -C "$dir" checkout -q --detach FETCH_HEAD
}

venv() {
  [ -x "$PY" ] || "${PYBOOT[@]}" -m venv .venv
}

keep_awake() {  # blocks system sleep until this bash process exits (display may still turn off)
  "$PY" -c 'import ctypes, sys
k = ctypes.windll.kernel32
k.SetThreadExecutionState.argtypes = [ctypes.c_uint]
k.OpenProcess.restype = ctypes.c_void_p
k.WaitForSingleObject.argtypes = [ctypes.c_void_p, ctypes.c_uint]
k.SetThreadExecutionState(0x80000001)  # ES_CONTINUOUS | ES_SYSTEM_REQUIRED
h = k.OpenProcess(0x00100000, False, int(sys.argv[1]))  # SYNCHRONIZE on the runner
while h and k.WaitForSingleObject(h, 60000) == 0x102:  # WAIT_TIMEOUT: runner alive
    pass' "$(cat /proc/$$/winpid)" &
}

binaries() {
  [ -f external/llama.cpp/build/bin/PREBUILT.txt ] && { cat external/llama.cpp/build/bin/PREBUILT.txt; return 0; }
  bash scripts/install_llama_win.sh
}

tests() {  # basetemp in logs/: %TEMP%\pytest-of-<user> on this machine denies access (WinError 5)
  "$PY" -m pip install -q "pytest>=8.0" && "$PY" -m pytest -q -p no:cacheprovider --basetemp=logs/pytest-tmp
}

wait_flag() {  # wait_flag NAME... -> prints the first flag file that appears
  local end=$((SECONDS + WAIT_SEC)) f
  while [ "$SECONDS" -lt "$end" ]; do
    for f in "$@"; do
      if [ -f "$f" ]; then rm -f "$f"; echo "$f"; return 0; fi
    done
    sleep 30
  done
  return 1
}

quality_small_first() {  # MODEL: smallest quant first, so heavily CPU-offloaded ones (F16) run last
  local q
  for q in Q2_K Q3_K_M Q4_K_M Q5_K_M Q6_K Q8_0 F16; do
    "$PY" src/perplexity_eval.py --model "$1" --quants "$q" &&
      "$PY" src/quality_eval.py --model "$1" --quants "$q" || return 1
  done
  "$PY" src/analyze.py
}

noise_floor() {  # identical re-runs: flips that happen without any change (src/consistency.py)
  local m q
  for m in Qwen2.5-1.5B-Instruct:F16 Qwen2.5-1.5B-Instruct:Q4_K_M Qwen2.5-3B-Instruct:Q4_K_M Qwen2.5-7B-Instruct:Q4_K_M; do
    q="${m#*:}"
    "$PY" src/quality_eval.py --model "${m%%:*}" --quants "$q" --out-root data/quality_rerun || return 1
  done
}

imatrix_stage() {  # collapsed low-bit quants: kernel check, imatrix re-quantization, then evaluate
  local m
  "$PY" src/imatrix_fix.py || return 1
  for m in Qwen2.5-3B-Instruct Qwen2.5-7B-Instruct; do
    "$PY" src/perplexity_eval.py --model "$m" --quants Q2_K-imat Q3_K_M-imat &&
      "$PY" src/quality_eval.py --model "$m" --quants Q2_K-imat Q3_K_M-imat || return 1
  done
}

determinism() {  # one llama-server slot, run twice: are re-run differences caused by concurrent batching?
  local m r
  for m in Qwen2.5-1.5B-Instruct Qwen2.5-7B-Instruct; do
    for r in data/quality_np1 data/quality_np1_rerun; do
      "$PY" src/quality_eval.py --model "$m" --quants Q4_K_M --parallel 1 --out-root "$r" || return 1
    done
  done
}

isolation() {  # isolation MODEL NP1_RUNS NP4_RUNS: one slot vs 4 slots, identical settings, F16 reference in every run
  local m=$1 q s r n
  for r in $(seq 1 "$(( $2 > $3 ? $2 : $3 ))"); do
    for s in 1 4; do
      n=$3; [ "$s" = 1 ] && n=$2
      [ "$r" -le "$n" ] || continue
      for q in F16 Q8_0 Q6_K Q4_K_M; do
        "$PY" src/quality_eval.py --model "$m" --quants "$q" --parallel "$s" --out-root "data/isolation/np${s}_r$r" || return 1
      done
    done
  done
  "$PY" src/isolation.py
}

cleanup() {
  [ -d models ] || return 0
  mkdir -p _to_delete && mv models "_to_delete/models-$(date +%Y%m%d-%H%M%S)"
}

main() {
  step preflight preflight &&
  step repo repo &&
  step llama_src llama_src &&
  step venv venv &&
  { keep_awake; true; } &&
  step binaries binaries &&
  step setup bash scripts/setup.sh &&
  step tests tests &&
  step pipeline bash scripts/run_all.sh --stage all &&
  step pipeline_1.5b bash scripts/run_all.sh --stage all --model Qwen2.5-1.5B-Instruct &&
  step pipeline_3b bash scripts/run_all.sh --stage all --model Qwen2.5-3B-Instruct &&
  step pipeline_14b bash scripts/run_all.sh --stage ctx --model Qwen2.5-14B-Instruct &&
  step quality_14b quality_small_first Qwen2.5-14B-Instruct &&
  step noise_floor noise_floor &&
  step imatrix imatrix_stage &&
  step capacity "$PY" src/loadtest.py &&
  step deploy_demo "$PY" src/deploy.py --items 20 --capacity &&
  step determinism determinism
}

main_paper() {  # QB_MODE=paper: only what the cause-isolation experiment needs (models 1.5B and 7B)
  step preflight preflight &&
  step repo repo &&
  step llama_src llama_src &&
  step venv venv &&
  { keep_awake; true; } &&
  step binaries binaries &&
  step setup bash scripts/setup.sh &&
  step tests tests &&
  step models_1.5b bash scripts/quantize.sh Qwen2.5-1.5B-Instruct &&
  step models_7b bash scripts/quantize.sh Qwen2.5-7B-Instruct &&
  step iso_1.5b isolation Qwen2.5-1.5B-Instruct 2 5 &&
  step iso_7b isolation Qwen2.5-7B-Instruct 2 3
}

run_main() { if [ "${QB_MODE:-}" = paper ]; then main_paper; else main; fi; }

PYBOOT=()
rm -f RETRY CLEANUP
while true; do
  if run_main; then
    status "ALL STAGES DONE - waiting for CLEANUP while Claude checks the results"
    case "$(wait_flag CLEANUP RETRY)" in
      CLEANUP) cleanup && status "FINISHED - models moved to _to_delete (delete that folder yourself)"; exit 0 ;;
      RETRY) status "RETRY received"; exec bash "$0" ;;
      *) status "no CLEANUP within 12 h - models kept"; exit 0 ;;
    esac
  else
    status "WAITING for a fix (RETRY file). Details: logs/runner.log"
    if [ "$(wait_flag RETRY)" = RETRY ]; then status "RETRY received"; exec bash "$0"; fi
    status "no RETRY within 12 h - exiting"
    exit 1
  fi
done
